function analyzeWarThunder(input: string): string {
  const s = input.toLowerCase();
  const issues: string[] = [];
  const tips: string[] = [];

  // Анализ по ключевым словам из описания/файла
  if (s.includes('погиб в лоб') || s.includes('убило в лоб') || s.includes('сгорел')) {
    issues.push('Ты часто подставляешь корпус под выстрелы противника — старайся показывать врагу только башню (или минимальный силуэт) из-за укрытия.');
    tips.push('Изучи карту: знай, откуда обычно стреляют, и перемещайся от укрытия к укрытию.');
  }
  if (s.includes('снайпер') || s.includes('не попал') || s.includes('промах') || s.includes('промазал')) {
    issues.push('Промахи на средней дистанции — признак плохого упреждения. Тренируй стрельбу по движущимся целям.');
    tips.push('В бою используй упреждение в 1.5-2 корпуса на дистанции 500-800 м, пристреляйся заранее на полигоне.');
  }
  if (s.includes('засветили') || s.includes('обнаружили') || s.includes('заметили меня') || s.includes('ослепили')) {
    issues.push('Ты часто светишься на открытой местности без укрытия — это основная причина поражения.');
    tips.push('Двигайся за холмами и домами, не вылезай на чистое поле без разведки (бинокль, дрон).');
  }
  if (s.includes('не успел') || s.includes('поздно') || s.includes('опоздал') || s.includes('не поспел')) {
    issues.push('Ошибки с таймингом: ты приходишь на точки слишком поздно или слишком рано.');
    tips.push('Смотри на таймер матча, держи ритм: занимай позицию к началу боя, не задерживайся на базе.');
  }
  if (s.includes('спазмил') || s.includes('рванул в бой') || s.includes('один на пятерых') || s.includes('зашёл один')) {
    issues.push('Ты врываешься в одиночку против 2+ противников без поддержки команды.');
    tips.push('Играй с командой: подожди напарников, координируй атаку, не ныряй в одиночку.');
  }
  if (s.includes('сносить') || s.includes('таран') || s.includes('таранил')) {
    issues.push('Таран — редкий и опасный приём: в 90% случаев ты теряешь технику зря.');
    tips.push('Лучше зайди с фланга и выстрели в борт, чем идти на таран.');
  }
  if (s.includes('горел') || s.includes('пожар') || s.includes('двигатель') || s.includes('перебило гусеницу') || s.includes('обездвижен')) {
    issues.push('Критические повреждения ходовой/двигателя — результат попаданий в открытые зоны.');
    tips.push('Ремонт в укрытии, чинись за стеной или дымом, не стой на виду.');
  }
  if (s.includes('не знал карту') || s.includes('впервые на карте') || s.includes('заблудился')) {
    issues.push('Плохое знание карты приводит к неправильным позициям и гибели.');
    tips.push('Проведи 15 минут в режиме тренировки/наблюдение, выучи ключевые точки и маршруты.');
  }
  if (s.includes('смена боеприпасов') || s.includes('не переключил снаряд') || s.includes('обычный снаряд против брони') || s.includes('фугас по танку')) {
    issues.push('Ты использовал неправильный тип снаряда — это критично для пробития.');
    tips.push('Всегда имей запас бронебойных (БП) и используй их против танков, кумулятивные — против лёгкой техники, фугасные — против открытых целей (САУ, лёгкие танки).');
  }
  if (s.includes('член вылетел из боя') || s.includes('дисконнект') || s.includes('вылетел из-за интернета') || s.includes('не зашёл в бой')) {
    issues.push('Проблемы с подключением мешают стабильной игре — это не игровые ошибки, но влияют на результат.');
    tips.push('Используй проводное подключение, проверь пинг (30-60 мс идеально для наземных боёв), закрой фоновые загрузки.');
  }

  if (issues.length === 0) {
    issues.push('По твоему описанию сложно выделить конкретные ошибки — опиши бой подробнее (что за техника, карта, где погиб, какие были выстрелы). Если скинул файл реплея, убедись, что это текстовый формат (.txt/.log), который можно прочитать.');
    tips.push('Изучи базовые позиции (sniping spots) на карте и практикуйся в стрельбе по движущимся целям.');
  }

  return `📊 Разбор боя в War Thunder

🔍 Что сделано не так (ошибки):
${issues.map((i) => '• ' + i).join('\n')}

💡 Как исправить (советы):
${tips.map((t) => '• ' + t).join('\n')}

🎯 Главный вывод: работай над позиционированием и типом снарядов — это даст +50% к выживаемости. Постоянная игра в одиночку без плана — главная причина большинства поражений. Удачных боёв!`;
}

